"""Generate alpha.20 anchor mesh/textures/model wiring from authored patterns.
Run from repo root: python3 scripts/generate_anchor.py (Python standard library).
Dimensions in Minecraft pixels: height 12, maximum diameter 8, timber 7.4. All circular profiles have 16 sides.
Wood references Minecraft oak; original muted-brown rope uses a connected strand pattern. A translucent wear layer
is authored separately. Alpha.12 paint/cap texture generation is locked.
Top-level OBJ objects allow the placed rope to follow CONNECTED state.
"""
from pathlib import Path
import json, math, struct, zlib

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/main/resources/assets/builders_balloon'
MODELS = ASSETS / 'models/block/balloon_tether'
TEXTURES = ASSETS / 'textures/block/anchor'
COLORS = dict(zip('white orange magenta light_blue yellow lime pink gray light_gray cyan purple blue brown green red black'.split(),
    (0xF9FFFE,0xF9801D,0xC74EBD,0x3AB3DA,0xFED83D,0x80C71F,0xF38BAA,0x474F52,0x9D9D97,0x169C9C,0x8932B8,0x3C44AA,0x835432,0x5E7C16,0xB02E26,0x1D1D21)))

def noise(x,y,seed=0):
    return ((x*374761393+y*668265263+seed*1274126177) ^ ((x+y+seed)*2246822519)) % 101

def rgb(value): return ((value >> 16)&255,(value >> 8)&255,value&255)
def shade(color,delta): return tuple(max(0,min(255,c+delta)) for c in color)
def blend(a,b,t): return tuple(round(x*(1-t)+y*t) for x,y in zip(a,b))
def cap_wood(x,y):
    # Coarse connected fissures and irregular worn grain, not evenly spaced stripes.
    x%=32;y%=16
    region=noise(x//3,y//4,21)
    c=(149,119,82) if region<37 else (129,98,65) if region<70 else (164,136,99)
    for cx,start,length,width in [(1,2,8,2),(5,7,8,2),(10,0,6,2),(13,5,7,3),(19,1,10,2),(24,6,8,2),(28,0,7,2)]:
        wobble=(y//3+cx)%3-1
        distance=(x-cx-wobble)%32
        if start<=y<start+length:
            if distance<width:c=(91,68,43) if distance==0 else (111,82,51)
            elif distance==width:c=(173,142,101)
    # Larger bleached rubbing patches and dirt at the foot.
    if 6<=x<=9 and 2<=y<=6:c=blend(c,(181,155,117),.55)
    if 20<=x<=23 and 8<=y<=11:c=blend(c,(172,144,107),.6)
    if y>12:c=blend(c,(77,64,47),(y-12)*.075)
    return shade(c,noise(x//2,y//2,23)//25-2)

def png(path,w,h,pixel):
    # New pixels only; no input image or third-party texture is sampled.
    rows = b''.join(b'\x00'+bytes(c for x in range(w) for c in ((lambda p: (*p,255) if len(p)==3 else p)(pixel(x,y)))) for y in range(h))
    def chunk(kind,data): return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff)
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',w,h,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(rows,9))+chunk(b'IEND',b''))

def write_json(path,data): path.write_text(json.dumps(data,indent=2)+'\n')

def anchor_y(y,group):
    if group=='Mount':return y
    if group=='Rope':return y-4
    if y<=2.3:return y
    if y<9.9:return 2.3+(y-2.3)*(5.9-2.3)/(9.9-2.3)
    return y-4

class Mesh:
    def __init__(self):
        self.lines=['# Original Builder\'s Balloon anchor; generated by scripts/generate_anchor.py','mtllib anchor.mtl'];self.count=0;self.wear_faces=[]
    def group(self,name): self.lines.append('o '+name)
    def face(self,points,material,uv=None):
        if uv is None:
            uv=([(0,0),(.25,0),(.25,.5),(0,.5)]
                if material=='Rope' else [(0,0),(1,0),(1,1),(0,1)])[:len(points)]
        if material in ('Wood','Stripped') and uv is not None:
            offset=math.floor(min(u for u,v in uv)*2+1e-8)
            uv=[(u*2-offset,v) for u,v in uv]
            if material=='Wood':self.wear_faces.append((points,uv))
        self.lines.append('usemtl '+material)
        for p in points: self.lines.append('v '+' '.join(f'{v/16:.7f}' for v in p))
        for u,v in uv: self.lines.append(f'vt {u:.7f} {v:.7f}')
        self.lines.append('f '+' '.join(f'{self.count+i+1}/{self.count+i+1}' for i in range(len(points))))
        self.count+=len(points)
    def profile(self,rings,material,cap_top=None,cap_bottom=None):
        # Counterclockwise in x/z, winding reversed at the top for upward normals.
        rings=[[(8+r*math.cos(a*math.pi/8+math.pi/16),y,8+r*math.sin(a*math.pi/8+math.pi/16)) for a in range(16)] for y,r in rings]
        for low,high in zip(rings,rings[1:]):
            for i in range(16):
                j=(i+1)%16
                # Only the vertical recessed wall is cut wood; shoulders retain bark.
                radial=lambda p:math.hypot(p[0]-8,p[2]-8)
                face_material='Stripped' if material=='Wood' and abs(radial(low[i])-2.95)<1e-6 and abs(radial(high[i])-2.95)<1e-6 else material
                self.face([low[i],high[i],high[j],low[j]],face_material,
                    [(i/16,low[i][1]/16),(i/16,high[i][1]/16),((i+1)/16,high[j][1]/16),((i+1)/16,low[j][1]/16)])
        for ring,mat,reverse in ((rings[0],cap_bottom,False),(rings[-1],cap_top,True)):
            if mat:
                for i in range(16):
                    pts=[(8,ring[0][1],8),ring[i],ring[(i+1)%16]]
                    if reverse: pts.reverse()
                    self.face(pts,mat,[((x-4)/8,(z-4)/8) for x,y,z in pts])
    def box(self,lo,hi,mat):
        x,y,z=lo;X,Y,Z=hi
        for face in [[(x,y,z),(x,Y,z),(X,Y,z),(X,y,z)],[(X,y,Z),(X,Y,Z),(x,Y,Z),(x,y,Z)],
            [(x,y,Z),(x,Y,Z),(x,Y,z),(x,y,z)],[(X,y,z),(X,Y,z),(X,Y,Z),(X,y,Z)],
            [(x,Y,z),(x,Y,Z),(X,Y,Z),(X,Y,z)],[(x,y,Z),(x,y,z),(X,y,z),(X,y,Z)]]: self.face(face,mat)
    def rope_ring(self,y):
        # Sixteen-sided wrap with square cross-section aligned to the local radial plane.
        rings=[]
        for radial,vertical in ((-.45,-.38),(.45,-.38),(.45,.38),(-.45,.38)):
            rings.append([(8+(3.45+radial)*math.cos(i*math.pi/8+math.pi/16),y+vertical,8+(3.45+radial)*math.sin(i*math.pi/8+math.pi/16)) for i in range(16)])
        for k in range(4):
            nxt=(k+1)%4
            for i in range(16):
                j=(i+1)%16
                self.face([rings[k][i],rings[nxt][i],rings[nxt][j],rings[k][j]],'Rope',[(i/16,0),(i/16,.5),((i+1)/16,.5),((i+1)/16,0)])

def main():
    TEXTURES.mkdir(parents=True,exist_ok=True)
    # Connected slanted strands, using an eight-pixel cross-section in the actual UVs.
    def rope_pixel(x,y):
        phase=(x+(y%8)//2)%8
        tones=[(88,75,63),(109,94,81),(128,112,98),(144,128,113),
               (157,142,126),(148,132,116),(132,115,100),(112,96,83)]
        return shade(tones[phase],(0,1,0,-1)[(x//8)%4])
    png(TEXTURES/'rope.png',32,16,rope_pixel)
    # Shader alpha is sampled before material alpha, matching the existing wear pass.
    png(TEXTURES/'contact_shadow.png',16,16,lambda x,y:(43,32,24,round(135*(1-y/15)**2)))
    def dark_steel(x,y):
        # Keep the dark sleeve. Put readable scuffs/corrosion in its sampled side
        # band: original vertical Mount UVs use rows 13-15 of this 16-pixel tile.
        c=shade((64,69,71),noise(x,y,4)//17-3)
        if 5<=x<=11 and 5<=y<=9:c=blend(c,(83,86,85),.5)
        if 21<=x<=25 and 6<=y<=11:c=blend(c,(43,48,51),.4)
        if y==13:
            c=shade(c,5)
            if x in (3,4,5,6,7,8,18,19,20,21,22,23):c=(88,92,92)
        if y==14 and x in (6,7,8,21,22):c=(83,87,87)
        if y==15:
            c=shade(c,-5)
            if x in (7,8,9,10):c=(77,81,82)
        if (x,y) in {(2,14),(3,14),(3,15),(4,15),(24,13),(25,13),(24,14)}:c=blend(c,(102,74,53),.60)
        if (x,y) in {(13,14),(14,14),(15,14),(14,15),(15,15)}:c=(43,48,50)
        return c
    png(TEXTURES/'metal.png',32,16,dark_steel)
    # A tiny dedicated fastener tile, rather than a whole sleeve texture per face.
    png(TEXTURES/'rivet.png',4,4,lambda x,y:shade((70,75,77),7 if y==0 else -3 if y==3 or x in (0,3) else 2))
    for name,color in COLORS.items():
        pigment=blend(rgb(color),(171,157,133),.23)
        def paint(x,y,pigment=pigment):
            # A connected, uneven edge with short runs, laid over weathered timber.
            edge=[5,5,6,7,6,5,4,5,6,7,7,6,5,4,5,5,6,7,6,5,4,5,6,6,5,4,5,6,7,6,5,5][x]
            if y>=edge:return cap_wood(x,y//2)
            dry=.15+noise(x//3,y//2,30)/400
            if x in (6,7,18,19,27):dry+=.22
            if y>=edge-2:dry+=.22
            return blend(pigment,cap_wood(x,y//2),min(dry,.62))
        png(TEXTURES/('paint_'+name+'.png'),32,32,paint)
        def cap(x,y,pigment=pigment):
            grain=int(math.hypot(x-7.5,y-7.5))%4
            wear=.12+noise(x//3,y//3,31)/380
            if (x<4 and y>8) or (x>10 and 3<=y<=7):wear+=.28
            if grain==0:wear+=.12
            return blend(pigment,cap_wood(x*2,y),min(wear,.67))
        png(TEXTURES/('cap_'+name+'.png'),16,16,cap)
    mesh=Mesh();mesh.group('Timber')
    mesh.profile([(1.8,3.7),(9.9,3.7),(10.25,2.95),(11.85,2.95),(12.2,3.7)],'Wood')
    mesh.profile([(12.2,3.7),(15.7,3.7),(16,3.45)],'Paint',cap_top='PaintEnd')
    mesh.group('Mount')
    mesh.profile([(0,4),(0.4,4),(0.7,3.9),(2.1,3.9),(2.3,3.8)],'Metal',cap_top='Metal',cap_bottom='Metal')
    # Two small raised rivets on opposite exposed sides of the sleeve.
    mesh.box((7.7,.85,11.65),(8.3,1.45,11.9),'Rivet')
    mesh.box((7.7,.85,4.1),(8.3,1.45,4.35),'Rivet')
    mesh.group('Rope');mesh.rope_ring(10.64);mesh.rope_ring(11.46)
    mesh.box((7.4,10.3,11.15),(8.6,11.8,12.15),'Rope')
    mesh.box((8.1,9.7,11.25),(8.75,10.75,11.95),'Rope')
    # Preserve original UVs, paint proportions and all rope/sleeve dimensions.
    group=None
    for i,line in enumerate(mesh.lines):
        if line.startswith('o '):group=line.split()[1]
        elif line.startswith('v '):
            x,y,z=map(float,line.split()[1:])
            mesh.lines[i]='v '+' '.join(f'{v:.7f}' for v in (x,anchor_y(y*16,group)/16,z))
    wear=Mesh();wear.lines[1]='mtllib weathering.mtl';wear.group('Weathering')
    for points,uv in mesh.wear_faces:
        points=[(x,anchor_y(y,'Timber'),z) for x,y,z in points]
        a,b,c=points[:3]
        ab=[b[i]-a[i] for i in range(3)];ac=[c[i]-a[i] for i in range(3)]
        n=[ab[1]*ac[2]-ab[2]*ac[1],ab[2]*ac[0]-ab[0]*ac[2],ab[0]*ac[1]-ab[1]*ac[0]]
        length=math.sqrt(sum(v*v for v in n));n=[v/length*.01 for v in n]
        wear.face([tuple(p[i]+n[i] for i in range(3)) for p in points],'Weathering',uv)
    (MODELS/'weathering.obj').write_text('\n'.join(wear.lines)+'\n')
    (MODELS/'weathering.mtl').write_text('newmtl Weathering\nKa 0 0 0\nKd 1 1 1 0.333333333\nmap_Kd #weathering\nforge_TintIndex -1\n')
    def weathering(x,y):
        alpha=12;col=(165,151,126)
        if 4<=x<=8 and 3<=y<=8:alpha=35;col=(182,170,144)
        if 18<=x<=22 and 7<=y<=11:alpha=30;col=(180,165,135)
        if y>=12:alpha=18+(y-12)*8;col=(57,49,38)
        if (x==12 and 5<=y<=10) or (x==25 and 1<=y<=6):alpha=48;col=(63,50,34)
        # Entity shaders discard sampled alpha < 0.1 before vertex tint.
        # Triple the sample and apply 1/3 material alpha to keep the approved wear.
        return (*col,alpha*3)
    png(TEXTURES/'weathering.png',32,16,weathering)
    write_json(MODELS/'weathering.json',{'loader':'neoforge:obj','model':'builders_balloon:models/block/balloon_tether/weathering.obj',
        'parent':'block/block','automatic_culling':False,'flip_v':True,'render_type':'translucent',
        'textures':{'particle':'minecraft:block/oak_log','weathering':'builders_balloon:block/anchor/weathering'}})
    (MODELS/'anchor.obj').write_text('\n'.join(mesh.lines)+'\n')
    (MODELS/'anchor.mtl').write_text('\n'.join(f'newmtl {name}\nKa 0 0 0\nKd 1 1 1\nmap_Kd #{texture}\nforge_TintIndex -1\n' for name,texture in [('Wood','wood'),('Stripped','stripped'),('Metal','metal'),('Rivet','rivet'),('Rope','wrap'),('Paint','paint'),('PaintEnd','paint_end')]))
    base={'loader':'neoforge:obj','model':'builders_balloon:models/block/balloon_tether/anchor.obj','parent':'block/block',
        'automatic_culling':False,'flip_v':True,'render_type':'cutout','textures':{'particle':'builders_balloon:block/anchor/wood',
        **{name:'builders_balloon:block/anchor/'+file for name,file in [('wood','wood'),('metal','metal'),('rivet','rivet'),('wrap','wrap'),('paint','paint_blue'),('paint_end','cap_blue')]}},
        'visibility':{'Timber':True,'Mount':True,'Rope':False}}
    base['textures']['wood']='minecraft:block/oak_log'
    base['textures']['stripped']='minecraft:block/stripped_oak_log'
    base['textures']['particle']='minecraft:block/oak_log'
    base['textures']['wrap']='builders_balloon:block/anchor/rope'
    atlas=ROOT/'src/main/resources/assets/minecraft/atlases/blocks.json'
    # The custom rope is a block sprite; no entity sprite atlas addition is needed.
    if atlas.exists():atlas.unlink()
    write_json(MODELS/'model.json',base)
    write_json(MODELS/'rope.json',{'parent':'builders_balloon:block/balloon_tether/model','visibility':{'Timber':False,'Mount':False,'Rope':True}})
    overrides=[]
    for index,color in enumerate(COLORS):
        write_json(MODELS/('anchor_'+color+'.json'),{'parent':'builders_balloon:block/balloon_tether/model',
            'textures':{'paint':'builders_balloon:block/anchor/paint_'+color,'paint_end':'builders_balloon:block/anchor/cap_'+color}})
        write_json(ASSETS/('models/item/balloon_tether_'+color+'.json'),{'parent':'builders_balloon:block/balloon_tether/anchor_'+color,
            'visibility':{'Rope':True},'display':{'gui':{'rotation':[30,225,0],'translation':[0,0,0],'scale':[.85,.85,.85]},
            'ground':{'translation':[0,3,0],'scale':[.5,.5,.5]},'fixed':{'scale':[.75,.75,.75]},
            'thirdperson_righthand':{'rotation':[75,45,0],'translation':[0,2.5,0],'scale':[.5,.5,.5]},
            'thirdperson_lefthand':{'rotation':[75,225,0],'translation':[0,2.5,0],'scale':[.5,.5,.5]},
            'firstperson_righthand':{'rotation':[0,45,0],'translation':[0,0,0],'scale':[.65,.65,.65]},
            'firstperson_lefthand':{'rotation':[0,225,0],'translation':[0,0,0],'scale':[.65,.65,.65]}}})
        item_path=ASSETS/('models/item/balloon_tether_'+color+'.json')
        item=json.loads(item_path.read_text())
        item.pop('visibility')
        item.update({'loader':'neoforge:composite','parent':'block/block',
            'textures':{'particle':'minecraft:block/oak_log'},
            'children':{'anchor':{'parent':'builders_balloon:block/balloon_tether/anchor_'+color,'visibility':{'Rope':True}},
                'weathering':{'parent':'builders_balloon:block/balloon_tether/weathering'}},
            'item_render_order':['anchor','weathering']})
        write_json(item_path,item)
        overrides.append({'predicate' :{'builders_balloon:color':index},'model':'builders_balloon:item/balloon_tether_'+color})
    write_json(ASSETS/'models/item/balloon_tether.json',{'parent':'builders_balloon:item/balloon_tether_white','overrides':overrides})
    # Local spin meshes keep vanilla mounting rotations valid on all six faces.
    def rotated_obj(text,spin):
        lines=[]
        for line in text.splitlines():
            if line.startswith('v '):
                x,y,z=map(float,line.split()[1:]);x-=.5;z-=.5
                x,z=[(x,z),(-z,x),(-x,-z),(z,-x)][spin]
                line='v '+' '.join(f'{v:.7f}' for v in (x+.5,y,z+.5))
            lines.append(line)
        return '\n'.join(lines)+'\n'
    shadow=Mesh();shadow.lines[1]='mtllib contact_shadow.mtl';shadow.group('ContactShadow')
    # Only bark shoulders; no wood or groove texture is edited.
    for points,uv in mesh.wear_faces:
        ys={round(p[1],2) for p in points}
        if ys not in ({9.9,10.25},{11.85,12.2}):continue
        points=[(x,anchor_y(y,'Timber'),z) for x,y,z in points]
        a,b,c=points[:3];ab=[b[i]-a[i] for i in range(3)];ac=[c[i]-a[i] for i in range(3)]
        n=[ab[1]*ac[2]-ab[2]*ac[1],ab[2]*ac[0]-ab[0]*ac[2],ab[0]*ac[1]-ab[1]*ac[0]]
        length=math.sqrt(sum(v*v for v in n));n=[v/length*.02 for v in n]
        # Inner edge receives the shadow; outer edge fades to zero.
        tex_uv=[(i/3,1 if math.hypot(x-8,z-8)<3.3 else 0) for i,(x,y,z) in enumerate(points)]
        shadow.face([tuple(p[i]+n[i] for i in range(3)) for p in points],'ContactShadow',tex_uv)
    (MODELS/'contact_shadow.obj').write_text('\n'.join(shadow.lines)+'\n')
    (MODELS/'contact_shadow.mtl').write_text('newmtl ContactShadow\nKa 0 0 0\nKd 1 1 1 0.333333333\nmap_Kd #contact_shadow\nforge_TintIndex -1\n')
    write_json(MODELS/'contact_shadow.json',{'loader':'neoforge:obj','parent':'block/block',
        'model':'builders_balloon:models/block/balloon_tether/contact_shadow.obj','flip_v':True,
        'automatic_culling':False,'render_type':'translucent',
        'textures':{'contact_shadow':'builders_balloon:block/anchor/contact_shadow'}})
    for spin in range(1,4):
        for stem in ('anchor','weathering','contact_shadow'):
            (MODELS/(stem+'_spin'+str(spin)+'.obj')).write_text(rotated_obj((MODELS/(stem+'.obj')).read_text(),spin))
        for color in COLORS:
            variant=json.loads((MODELS/'model.json').read_text())
            variant['model']='builders_balloon:models/block/balloon_tether/anchor_spin'+str(spin)+'.obj'
            variant['textures']['paint']='builders_balloon:block/anchor/paint_'+color
            variant['textures']['paint_end']='builders_balloon:block/anchor/cap_'+color
            write_json(MODELS/('anchor_'+color+'_spin'+str(spin)+'.json'),variant)
        for stem,obj in (('weathering','weathering'),('rope','anchor'),('contact_shadow','contact_shadow')):
            variant=json.loads((MODELS/('model.json' if stem=='rope' else stem+'.json')).read_text())
            if stem=='rope':variant['visibility']={'Timber':False,'Mount':False,'Rope':True}
            variant['model']='builders_balloon:models/block/balloon_tether/'+obj+'_spin'+str(spin)+'.obj'
            write_json(MODELS/(stem+'_spin'+str(spin)+'.json'),variant)
    for color in COLORS:
        item_path=ASSETS/('models/item/balloon_tether_'+color+'.json')
        item=json.loads(item_path.read_text())
        item['children']['contact_shadow']={'parent':'builders_balloon:block/balloon_tether/contact_shadow'}
        item['item_render_order'].append('contact_shadow');write_json(item_path,item)
    multipart=[]
    rotations={'down':{},'up':{'x':180},'north':{'x':90,'y':180},'south':{'x':90},'west':{'x':90,'y':90},'east':{'x':90,'y':270}}
    for direction,rotation in rotations.items():
        for spin in range(4):
            suffix='' if spin==0 else '_spin'+str(spin)
            for color in COLORS:
                multipart.append({'when':{'direction':direction,'spin':spin,'color':color},'apply':{'model':'builders_balloon:block/balloon_tether/anchor_'+color+suffix,**rotation}})
            multipart.append({'when':{'direction':direction,'spin':spin},'apply':{'model':'builders_balloon:block/balloon_tether/weathering'+suffix,**rotation}})
            for stem in ('rope','contact_shadow'):
                multipart.append({'when':{'direction':direction,'spin':spin,'connected':True},'apply':{'model':'builders_balloon:block/balloon_tether/'+stem+suffix,**rotation}})
    write_json(ASSETS/'blockstates/balloon_tether.json',{'multipart':multipart})
    print(f'Generated {len(multipart)} blockstate parts, four fixed spins, strand UVs and {shadow.count//4} contact-shadow quads.')

if __name__=='__main__': main()
